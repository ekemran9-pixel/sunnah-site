#!/usr/bin/env python3
"""Builds the GitHub Pages site from src/app.html into the repo root and docs/: full HTML document, local fonts, manifest and offline service worker."""
import hashlib, os, re, shutil

ROOT = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(ROOT, "docs")

page = open(os.path.join(ROOT, "src", "app.html"), encoding="utf-8").read()
# Google Fonts → self-hosted copies so the app works offline
page = re.sub(r'<link rel="preconnect"[^>]*>\n', "", page)
page = re.sub(r'<link rel="stylesheet" href="https://fonts.googleapis.com[^>]*>', '<link rel="stylesheet" href="fonts.css">', page)

head = """<!doctype html>
<html lang="bn">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="নবী মুহাম্মাদ ﷺ-এর দৈনিক রুটিন, জীবনী, উপদেশ, করণীয়-বর্জনীয় ও সুন্নাহ ট্র্যাকার।">
<meta name="theme-color" content="#0f5c4d">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<meta name="apple-mobile-web-app-title" content="সুন্নাহর পথে">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" href="icons/icon-192.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}[hidden]{display:none!important}img{max-width:100%}</style>
"""
title_end = page.index("</style>") + len("</style>")
html = head + page[:title_end] + "\n</head>\n<body>\n" + page[title_end:] + """
<script>
if ("serviceWorker" in navigator) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register("sw.js").then(reg => {
      navigator.serviceWorker.addEventListener("controllerchange", () => { if (location.hash === "" || location.hash === "#today") render(true) });
    }).catch(() => {});
  });
}
</script>
</body>
</html>
"""
open(os.path.join(DOCS, "index.html"), "w", encoding="utf-8").write(html)

assets = ["./", "index.html", "fonts.css", "manifest.webmanifest"]
for sub in ("fonts", "icons"):
    assets += [f"{sub}/{f}" for f in sorted(os.listdir(os.path.join(DOCS, sub)))]
h = hashlib.sha256()
for a in assets[1:]:
    h.update(open(os.path.join(DOCS, a), "rb").read())
version = h.hexdigest()[:10]

sw = f"""// সুন্নাহর পথে — offline service worker (generated by build.py)
const CACHE = "sunnah-{version}";
const ASSETS = {assets!r};

self.addEventListener("install", e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async cache => {{
    const hit = await cache.match(req, {{ignoreSearch: true}}) || (req.mode === "navigate" ? await cache.match("index.html") : null);
    const net = fetch(req).then(res => {{ if (res.ok) cache.put(req, res.clone()); return res }}).catch(() => hit);
    return hit || net;
  }}));
}});
"""
open(os.path.join(DOCS, "sw.js"), "w", encoding="utf-8").write(sw)
# Same site at the repo root, so Pages works whether it serves "/" or "/docs"
for f in ["index.html", "sw.js", "fonts.css", "manifest.webmanifest"]:
    shutil.copy(os.path.join(DOCS, f), os.path.join(ROOT, f))
for d in ["fonts", "icons"]:
    shutil.copytree(os.path.join(DOCS, d), os.path.join(ROOT, d), dirs_exist_ok=True)
print("built", version, len(assets), "assets")
